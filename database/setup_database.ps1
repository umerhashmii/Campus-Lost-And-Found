# ========================================================
# Database Setup & Verification Script
# Executes all schema, seeds, procedures, triggers, and views
# ========================================================

$mysqlBin = "C:\Program Files\MySQL\MySQL Server 8.0\bin\mysql.exe"
$user = "root"
$pass = "admin123"
$baseDir = "c:\University\DBMS Project 4th Semester\database"

$files = @(
    "01_schema.sql",
    "02_seed_data.sql",
    "03_procedures_and_concurrency.sql",
    "04_triggers.sql",
    "05_views.sql",
    "06_production_migration.sql"
)

Write-Host "================================================="
Write-Host "Setting up Campus Lost & Found Database..."
Write-Host "================================================="

foreach ($file in $files) {
    $fullPath = Join-Path $baseDir $file
    Write-Host "Applying: $file ... "
    Get-Content $fullPath -Raw | & $mysqlBin -u $user "-p$pass" --default-character-set=utf8mb4
    if ($LASTEXITCODE -eq 0) {
        Write-Host " -> OK"
    } else {
        Write-Host " -> FAILED"
        exit 1
    }
}

Write-Host "`nRunning Initial Match Engine for Seed Lost Reports..."
$initMatches = @"
USE campus_lost_and_found;
CALL sp_GenerateMatchesForLostReport(1);
CALL sp_GenerateMatchesForLostReport(2);
CALL sp_GenerateMatchesForLostReport(3);
CALL sp_GenerateMatchesForLostReport(4);
CALL sp_GenerateMatchesForLostReport(5);
"@
$initMatches | & $mysqlBin -u $user "-p$pass"

Write-Host "`nDatabase Verification - Table Row Counts:"
$verifySql = @"
USE campus_lost_and_found;
SELECT 'users' AS table_name, COUNT(*) AS count FROM users
UNION ALL SELECT 'locations', COUNT(*) FROM locations
UNION ALL SELECT 'categories', COUNT(*) FROM categories
UNION ALL SELECT 'lost_reports', COUNT(*) FROM lost_reports
UNION ALL SELECT 'found_reports', COUNT(*) FROM found_reports
UNION ALL SELECT 'matches', COUNT(*) FROM matches
UNION ALL SELECT 'claims', COUNT(*) FROM claims
UNION ALL SELECT 'notifications', COUNT(*) FROM notifications;
"@
$verifySql | & $mysqlBin -u $user "-p$pass" -t

Write-Host "`nPreviewing Matches Generated by Matching Algorithm:"
$matchFeedSql = "USE campus_lost_and_found; SELECT match_id, match_score, lost_item_name, found_item_name, category_name FROM vw_active_match_feed;"
$matchFeedSql | & $mysqlBin -u $user "-p$pass" -t

Write-Host "`nCampus Lost & Found Database Setup Complete!"
